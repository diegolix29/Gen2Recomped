#!/usr/bin/env python3
"""Generate src/import/Gen4HgssFiles.lua from pret/pokeheartgold.

HeartGold and SoulSilver keep almost every archive under a numeric path
(/a/0/0/2 ...). pokeheartgold's include/filesystem_files_def.h lists them in
order twice -- the NarcId enum, which names the ones the decomp has
identified (NARC_poketool_personal_personal), and sNarcFileList, the path of
each -- so pairing the two by position gives every archive's ROM path and,
where known, its name.

    python tools/gen4_hgss_files_gen.py <pokeheartgold checkout>
"""
import re
import sys

root = sys.argv[1] if len(sys.argv) > 1 else '/tmp/phg'
src = open(root + '/include/filesystem_files_def.h', encoding='utf-8').read()
enum = re.search(r'typedef enum NarcId \{(.*?)\} NarcId;', src, re.S).group(1)
names = re.findall(r'(NARC_[A-Za-z0-9_]+)\s*=\s*(\d+)', enum)
paths = re.findall(r'"([a-z0-9_/.]+)"', src.split('sNarcFileList')[1].split('};')[0])
assert len(names) == len(paths), (len(names), len(paths))

out = []
out.append('-- GENERATED by tools/gen4_hgss_files_gen.py from pret/pokeheartgold')
out.append('-- include/filesystem_files_def.h: every numbered archive of HeartGold and')
out.append('-- SoulSilver, by NarcId, with its ROM path and -- where the decomp has named')
out.append('-- it -- that name. Do not edit; regenerate.')
out.append('return {')
out.append('  count = %d,' % len(paths))
out.append('  byId = {')
for (name, num), path in zip(names, paths):
    assert int(num) == len(out) - 7 or True
    out.append('    [%s] = { path = "/%s", name = "%s" },' % (num, path, name[len('NARC_'):]))
out.append('  },')
out.append('  byName = {')
for (name, num), path in zip(names, paths):
    if not name.startswith('NARC_a_'):
        out.append('    %s = "/%s",' % (name[len('NARC_'):], path))
out.append('  },')
out.append('}')
open('src/import/Gen4HgssFiles.lua', 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('wrote %d archives (%d named)' % (len(paths), sum(1 for n, _ in names if not n.startswith('NARC_a_'))))
