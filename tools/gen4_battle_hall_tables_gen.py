# Generates src/import/Gen4BattleHallTables.lua from a pokeplatinum checkout:
# the Battle Hall's tables in src/overlay104/battle_hall_helpers.c, with every
# TRAINER_CLASS_ / SPECIES_ / TYPE_ name resolved to its number through the
# decomp's generated/*.txt lists (line index = value).
#
#   python tools/gen4_battle_hall_tables_gen.py <pokeplatinum> [out.lua]

import re
import subprocess
import sys
from pathlib import Path


def read(root, rel):
    p = Path(root) / rel
    if p.exists():
        return p.read_text(encoding="utf-8")
    return subprocess.run(["git", "-C", str(root), "show", "HEAD:" + rel],
                          capture_output=True, text=True, check=True).stdout


def enum(root, rel):
    names = [l.strip() for l in read(root, rel).splitlines() if l.strip()]
    return {n: i for i, n in enumerate(names)}


def body(src, name):
    m = re.search(re.escape(name) + r"\[[^=]*=\s*\{", src)
    if not m:
        raise SystemExit("not found: " + name)
    i, depth = m.end() - 1, 0
    for j in range(i, len(src)):
        if src[j] == "{":
            depth += 1
        elif src[j] == "}":
            depth -= 1
            if depth == 0:
                return src[i + 1:j]
    raise SystemExit("unbalanced: " + name)


def rows(text):
    return [re.findall(r"[A-Z_0-9]+", r) for r in re.findall(r"\{([^{}]*)\}", text)]


def main():
    root = sys.argv[1]
    out = sys.argv[2] if len(sys.argv) > 2 else "src/import/Gen4BattleHallTables.lua"
    src = read(root, "src/overlay104/battle_hall_helpers.c")
    classes = enum(root, "generated/trainer_classes.txt")
    species = enum(root, "generated/species.txt")
    types = enum(root, "generated/pokemon_types.txt")
    groups = {k: int(v) for k, v in re.findall(r"#define (GROUP_\d_START) (\d+)", src)}

    by_rank = [[classes[c] for c in r] for r in rows(body(src, "sHallTrainerClassesByRank"))]
    by_type = [[classes[c] for c in r] for r in rows(body(src, "sHallTrainerClassesBySelectedType"))]
    mon_types = [[types[t] for t in r] for r in rows(body(src, "sBattleHallPotentialOpponentTypes"))]
    mons = [species[s] for s in re.findall(r"SPECIES_[A-Z_0-9]+", body(src, "sBattleHallPotentialOpponents"))]
    ivs = [int(r[1]) for r in rows(body(src, "sIVsPerTypeRank"))]
    grid = []
    for t in re.findall(r"[A-Z_]+", body(src, "sBattleHallAppGridOrder")):
        grid.append(0xFE if t == "BATTLE_HALL_MON_SUMMARY" else types[t])
    assert len(mons) == len(mon_types), (len(mons), len(mon_types))
    assert len(by_rank) == 10 and all(len(r) == 8 for r in by_rank)
    assert len(by_type) == 18 and len(ivs) == 10 and len(grid) == 20

    def lst(xs):
        return "{ " + ", ".join(str(x) for x in xs) + " }"

    def lst0(xs):
        return "{ [0] = " + ", ".join(str(x) for x in xs) + " }"

    lines = [
        "-- GENERATED by tools/gen4_battle_hall_tables_gen.py from pokeplatinum's",
        "-- src/overlay104/battle_hall_helpers.c -- do not edit by hand.",
        "--",
        "-- Every table is 0-based, as the source indexes it. Classes are",
        "-- TRAINER_CLASS_* numbers, species SPECIES_* numbers, types TYPE_* numbers",
        "-- (TYPE_MYSTERY = 9); 0xFE in the grid is BATTLE_HALL_MON_SUMMARY.",
        "",
        "local T = {}",
        "",
        "-- GROUP_n_START (1-based positions in the opponent list)",
        "T.GROUP = { %d, %d, %d, %d }" % (groups["GROUP_1_START"], groups["GROUP_2_START"],
                                          groups["GROUP_3_START"], groups["GROUP_4_START"]),
        "-- sHallTrainerClassesByRank[rank][0..7]",
        "T.CLASSES_BY_RANK = { [0] = " + ",\n  ".join(lst0(r) for r in by_rank) + " }",
        "-- sHallTrainerClassesBySelectedType[typeIdx][0..3]",
        "T.CLASSES_BY_TYPE = { [0] = " + ",\n  ".join(lst0(r) for r in by_type) + " }",
        "-- sIVsPerTypeRank",
        "T.IVS = " + lst0(ivs),
        "-- sBattleHallAppGridOrder (cursor position -> type)",
        "T.GRID = " + lst0(grid),
        "-- sBattleHallPotentialOpponents: species, 0-based (pl_bsdpm member = index + 1)",
        "T.SPECIES = { [0] = " + ",\n  ".join(", ".join(str(s) for s in mons[i:i + 16])
                                        for i in range(0, len(mons), 16)) + " }",
        "T.COUNT = %d" % len(mons),
        "-- sBattleHallPotentialOpponentTypes",
        "T.MON_TYPES = { [0] = " + ",\n  ".join(", ".join(lst(t) for t in mon_types[i:i + 8])
                                          for i in range(0, len(mon_types), 8)) + " }",
        "",
        "return T",
        "",
    ]
    Path(out).write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print("wrote %s: %d opponents" % (out, len(mons)))


main()
