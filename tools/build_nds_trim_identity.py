"""Generate padding-independent identities from already verified local DS dumps.

Only hashes/sizes are written. Eight-MiB chunks bound verification's temporary
allocations on Android; no padded copy of a 128/256-MiB cartridge is needed.
"""
import hashlib
from pathlib import Path

ROMS = [
    ('heartgold', 'Pokemon - HeartGold Version (USA).nds', '4fcded0e2713dc03929845de631d0932ea2b5a37'),
    ('soulsilver', 'Pokemon - SoulSilver Version (USA, Australia).nds', 'f8dc38ea20c17541a43b58c5e6d18c1732c7e582'),
    ('black', 'Pokemon - Black Version (USA, Europe) (NDSi Enhanced).nds', '26ad0b9967aa279c4a266ee69f52b9b2332399a5'),
    ('white', 'Pokemon - White Version (USA, Europe) (NDSi Enhanced).nds', 'bc696a0dfb448c7b3a8a206f0f8214411a039208'),
]
CHUNK = 8 * 1024 * 1024
out = ['-- Generated by tools/build_nds_trim_identity.py from SHA-1-verified dumps.',
       '-- Every byte through the last non-FF byte is covered. Only trailing FF',
       '-- may be absent; these are identities, not cartridge content.',
       'return {', f'  chunkSize={CHUNK},', '  games={']
for version, filename, expected in ROMS:
    data = Path(filename).read_bytes()
    actual = hashlib.sha1(data).hexdigest()
    if actual != expected:
        raise SystemExit(f'{filename}: expected {expected}, got {actual}')
    meaningful = len(data.rstrip(b'\xff'))
    code = data[12:16].decode('ascii')
    out += [f"    {version}={{code='{code}',sha1='{expected}',",
            f'      capacity={len(data)},contentSize={meaningful},chunks={{']
    for offset in range(0, meaningful, CHUNK):
        digest = hashlib.sha1(data[offset:min(offset+CHUNK, meaningful)]).hexdigest()
        out.append(f"        '{digest}',")
    out += ['      }},']
out += ['  }', '}','']
Path('src/import/NdsTrimIdentity.lua').write_text('\n'.join(out), encoding='utf8')
print('Wrote padding-independent identities for', len(ROMS), 'verified cartridges')
