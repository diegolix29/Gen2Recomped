"""Generate src/import/Gen4HgssObjectGfx.lua from pret/pokeheartgold.

    python tools/gen4_hgss_sprites_gen.py [path to pokeheartgold]

HeartGold and SoulSilver's overworld-sprite table, ov01_022074A8 in
asm/overlay_01_sprite_data.s: one row per sprite id,

    .short SPRITE_<name>, MMODEL_<name>, <bits> | (<anim> << 10)

ending at SPRITE 0xFFFF. SPRITE_ ids are what a map's object events carry
(include/constants/sprites.h); MMODEL_ values are members of mmodel.narc
(include/constants/mmodel.h). The third short is kept as the asm spells it,
split into its low ten bits and its top six (`anim`). Constants are evaluated
from the headers, including the ones defined as sums of others.
"""
import os
import re
import sys

root = sys.argv[1] if len(sys.argv) > 1 else "/tmp/phg"


def defines(path, consts):
    for line in open(os.path.join(root, path), encoding="utf-8"):
        m = re.match(r"\s*#define\s+(\w+)\s+(.+?)\s*(//.*)?$", line)
        if m and not m.group(1).startswith("POKEHEARTGOLD"):
            consts[m.group(1)] = m.group(2)


raw = {}
for header in ("include/constants/follow_mon_idx.h", "include/constants/mmodel.h",
               "include/constants/sprites.h"):
    if os.path.exists(os.path.join(root, header)):
        defines(header, raw)


def value(expr, depth=0):
    expr = expr.strip()
    if depth > 20:
        raise ValueError(expr)
    if re.fullmatch(r"0x[0-9A-Fa-f]+|\d+", expr):
        return int(expr, 0)
    names = re.findall(r"[A-Za-z_]\w*", expr)
    env = {n: value(raw[n], depth + 1) for n in names if n in raw}
    missing = [n for n in names if n not in raw]
    if missing:
        raise KeyError(missing)
    return int(eval(expr, {"__builtins__": {}}, env))


asm = open(os.path.join(root, "asm/overlay_01_sprite_data.s"), encoding="utf-8").read()
table = asm.split("ov01_022074A8:")[1].split(".data")[0]
rows = []
for m in re.finditer(r"\.short\s+(\w+),\s*(\w+),\s*(0x[0-9A-Fa-f]+)\s*\|\s*\((\d+)\s*<<\s*10\)", table):
    sprite, model, low, anim = m.groups()
    sid = value(sprite) if sprite in raw else int(sprite, 0)
    if sid == 0xFFFF:
        break
    rows.append((sid, sprite, value(model), model, int(low, 16), int(anim)))

out = ["-- GENERATED by tools/gen4_hgss_sprites_gen.py from pret/pokeheartgold",
       "-- asm/overlay_01_sprite_data.s (ov01_022074A8) with sprites.h and mmodel.h.",
       "-- Do not edit; regenerate. byId[sprite] = { member, name, bits, anim }.",
       "return {", "  count = %d," % len(rows), "  byId = {"]
for sid, sprite, member, model, low, anim in rows:
    out.append('    [%d] = { %d, "%s", 0x%03X, %d },' % (sid, member, sprite[len("SPRITE_"):].lower(), low, anim))
out += ["  },", "}"]
dst = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "import", "Gen4HgssObjectGfx.lua")
open(dst, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print("%d sprite rows; members %d..%d" % (len(rows), min(r[2] for r in rows), max(r[2] for r in rows)))
