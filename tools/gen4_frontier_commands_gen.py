"""Generate src/import/Gen4FrontierCommands.lua from a pokeplatinum checkout.

    python tools/gen4_frontier_commands_gen.py <pokeplatinum dir>

Platinum's Battle Frontier scenes (overlay104) run their own script engine
over the fr_script NARC.  Its byte code is a u16 opcode followed by the
command's operands, and the operand layout of every opcode is stated by
asm/macros/frscrcmd.inc: the `.short FRSCRCMD_X` line and the `.short` /
`.byte` / `.long` lines after it, up to the next opcode or the end of the
macro.  The opcode NUMBERS are the order of include/data/scripts/frscrcmd.h.

The generated file is a table of facts about the cartridge's encoding --
names and operand widths -- read once here so the port never needs the
decomp to decode a script.  `.long \\offset-.-4` is a relative jump (s32 from
the end of the operand); other `.long`s are plain u32.
"""
import re, subprocess, sys, os

root = sys.argv[1]

def show(path):
    p = os.path.join(root, path)
    if os.path.exists(p):
        return open(p, encoding='utf-8').read()
    return subprocess.check_output(['git', '-C', root, 'show', 'HEAD:' + path]).decode('utf-8')

hdr = show('include/data/scripts/frscrcmd.h')
names = re.findall(r'ScriptCommand\((FRSCRCMD_\w+),\s*(\w+)\)', hdr)
ids = {n: i for i, (n, _) in enumerate(names)}

inc = show('asm/macros/frscrcmd.inc')
layout, macro_of = {}, {}
cur_macro, cur_ops, in_if, branch_ops = None, [], False, []
for raw in inc.splitlines():
    line = raw.split('@')[0].strip()
    m = re.match(r'\.macro\s+(\w+)', line)
    if m:
        cur_macro, cur_ops, in_if, branch_ops = m.group(1), [], False, []
        continue
    if line.startswith('.endm'):
        cur_macro, cur_ops = None, []
        continue
    if cur_macro is None:
        continue
    if line.startswith('.if'):
        in_if, branch_ops, cur_ops = True, [], []
        continue
    if line.startswith('.else'):
        cur_ops = []
        continue
    if line.startswith('.endif'):
        # operands after the conditional belong to whichever opcode it chose
        in_if, cur_ops = False, list(branch_ops)
        continue
    m = re.match(r'\.short\s+(FRSCRCMD_\w+)', line)
    if m:
        op = m.group(1)
        if op in layout:
            cur_ops = []
        else:
            layout[op] = []
            macro_of[op] = cur_macro
            cur_ops = [op]
            if in_if:
                branch_ops.append(op)
        continue
    kind = None
    if line.startswith('.short'):
        kind = 'u16'
    elif line.startswith('.byte'):
        kind = 'u8'
    elif line.startswith('.long'):
        kind = 'rel' if '-.-4' in line.replace(' ', '') else 'u32'
    if kind:
        for op in cur_ops:
            layout[op].append(kind)

moves = show('include/constants/battle_frontier_movements.h')
mv = [(n, str(int(v, 0))) for n, v in re.findall(r'#define\s+FRONTIER_MOVEMENT_(\w+)\s+(0x[0-9A-Fa-f]+|\d+)', moves)
      if n not in ('DELAY_OFFSET',) and not n.startswith('NUM_')]

out = []
out.append('-- GENERATED by tools/gen4_frontier_commands_gen.py from pokeplatinum\'s')
out.append('-- include/data/scripts/frscrcmd.h (opcode order) and asm/macros/frscrcmd.inc')
out.append('-- (operand widths).  Do not edit by hand.')
out.append('--')
out.append('-- [opcode] = { name, macro, operands }: "u8" / "u16" / "u32", "rel" a')
out.append('-- relative s32 offset from the end of the operand (a jump or a movement list).')
out.append('local C = {}')
out.append('C.ops = {')
missing = []
for i, (n, fn) in enumerate(names):
    args = layout.get(n)
    if args is None:
        missing.append(n)
        args = []
    nice = n[len('FRSCRCMD_'):].lower()
    out.append('  [%d] = { "%s", "%s", { %s } },' % (i, nice, macro_of.get(n, fn),
               ', '.join('"%s"' % a for a in args)))
out.append('}')
out.append('-- opcodes no macro emits (never seen in a script; decoded as operand-less)')
out.append('C.unmacroed = { %s }' % ', '.join('"%s"' % m[len('FRSCRCMD_'):].lower() for m in missing))
out.append('C.movements = {')
for name, val in mv:
    out.append('  [%s] = "%s",' % (val, name.lower()))
out.append('}')
out.append('C.SCRIPT_ENTRY_END = 0xFD13')
out.append('return C')
open('src/import/Gen4FrontierCommands.lua', 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
print('%d opcodes, %d with no macro, %d movements' % (len(names), len(missing), len(mv)))
