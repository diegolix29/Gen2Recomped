"""Generate src/import/Gen4HgssScriptOps.lua from pret/pokeheartgold.

    python tools/gen4_hgss_scrcmd_gen.py [path to pokeheartgold]

HeartGold and SoulSilver's script commands are NOT Platinum's: 854 of them,
renumbered. Their operand widths are READ from asm/macros/script.inc -- the
macros the cartridge's scripts were assembled with, so what a macro emits is
exactly what the bytes hold (a macro that takes an argument it never emits,
like ScrCmd_403's second, emits nothing for it, and neither does the ROM).

Each macro whose body opens with `.short <number>` is a command: the number is
the opcode and the .byte/.short/.hword/.word lines after it are the operands,
b/w/w/d. A macro that branches (.if) has no fixed width and is written as "*"
for the hand-written rules in the Lua module. Several macros may name one
opcode (aliases); they must agree on the width, and the first name is kept.
The command count comes from src/data/fieldmap/script_cmd_table.h.
"""
import os
import re
import sys

root = sys.argv[1] if len(sys.argv) > 1 else "/tmp/phg"
inc = open(os.path.join(root, "asm/macros/script.inc"), encoding="utf-8").read()
table = open(os.path.join(root, "src/data/fieldmap/script_cmd_table.h"), encoding="utf-8").read()
handlers = re.findall(r"^\s*(ScrCmd_\w+|\w+),\s*$", table.split("gScriptCmdTable[] = {")[1].split("};")[0], re.M)
count = len(handlers)

WIDTH = {".byte": "b", ".short": "w", ".hword": "w", ".word": "d"}
cmds, conflicts, jumps = {}, [], set()
for m in re.finditer(r"^\s*\.macro\s+(\w+)([^\n]*)\n(.*?)^\s*\.endm", inc, re.M | re.S):
    name, body = m.group(1), m.group(3)
    lines = [l.split("//")[0].strip() for l in body.split("\n")]
    lines = [l for l in lines if l]
    if not lines:
        continue
    first = re.match(r"^\.short\s+(\d+)$", lines[0])
    if not first:
        continue
    op = int(first.group(1))
    spec, variable, ok, relative = "", False, True, False
    for l in lines[1:]:
        if re.search(r"-\s*\.\s*-\s*4", l):
            relative = True  # `\dest-.-4`: a jump, relative to the operand's end
        d = l.split()[0]
        if d in WIDTH:
            spec += WIDTH[d]
        elif d.startswith(".if") or d in (".else", ".endif", ".elseif"):
            variable = True
        else:
            ok = False  # calls another macro: a compound, not one command
            break
    if not ok:
        continue
    if variable:
        spec = "*"
    if op in cmds:
        if cmds[op][1] != spec:
            conflicts.append((op, cmds[op], (name, spec)))
        continue
    cmds[op] = (name, spec)
    if relative:
        jumps.add(op)

if conflicts:
    for c in conflicts:
        print("CONFLICT", c)
    sys.exit(1)

missing = [i for i in range(count) if i not in cmds]
out = []
out.append("-- GENERATED by tools/gen4_hgss_scrcmd_gen.py from pret/pokeheartgold")
out.append("-- asm/macros/script.inc (the operand widths) and")
out.append("-- src/data/fieldmap/script_cmd_table.h (the count). Do not edit; regenerate.")
out.append("-- { macro name, lowercased name, spec }; \"*\" is variable (Gen4HgssScriptOps).")
out.append("return {")
out.append("  count = %d," % count)
out.append("  handlers = {")
for i, h in enumerate(handlers):
    out.append('    [%d] = "%s",' % (i, h))
out.append("  },")
out.append("  commands = {")
for op in sorted(cmds):
    if op >= count:
        continue
    name, spec = cmds[op]
    out.append('    [0x%03X] = { "%s", "%s" },' % (op, name, spec))
out.append("  },")
out.append("  -- commands whose last operand is a jump (`dest-.-4` in the macro);")
out.append("  -- ApplyMovement's points at movement data rather than code")
out.append("  relative = { %s }," % ", ".join("[0x%03X] = true" % j for j in sorted(jumps) if j < count))
out.append("}")
dst = os.path.join(os.path.dirname(__file__), "..", "src", "import", "Gen4HgssScriptTable.lua")
open(dst, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print("%d handlers, %d commands with macros, %d without: %s" % (count, len(cmds), len(missing), missing[:40]))
