#!/usr/bin/env python3
"""Bake the Emerald 3DS voxel data from the player's own Emerald ROM.

    python bake.py ROM [--payload DIR] [--out DIR]

The models, the relief and the signposts are not shipped with this mod: they
are made of the cartridge's own art, so -- exactly like Emerald 3DS's own
builder -- they are generated locally from the player's ROM.  This runs that
builder unchanged (its release payload: the recipe, the generator scripts and
the `emerald3ds_builder` package), checks every output against the CRCs the
release was built with, and copies the four voxel files out of the data pack
it writes:

    buildings.bin  relief.bin  regions.bin  signposts.bin

plus `layouts.lua`, the layout table (id -> name and tilesets) the generators
read, which the mod needs to tell which maps use the General tileset's trees.

With --generators DIR (a checkout of the Emerald 3DS repository, e.g. its
`dev` branch), that checkout's generator scripts and voxel assets are run
instead of the release's: the release's builder still turns the ROM into
the generators' input tree, but the outputs are newer than any release, so
there are no CRCs to check them against.

With no --payload, the v0.4.0 web payload is downloaded once from the Emerald
3DS GitHub release into generated/.payload/ (pruned from builds with the
rest of generated/).  Needs Python
3.11+ and Pillow.  Takes about fifteen minutes; the terrain relief is the slow
step.
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
import tempfile
import time
import urllib.request
import zipfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
PAYLOAD_URL = ("https://github.com/ZallaxDev/emerald-3ds/releases/download/v0.4.0/"
               "Emerald3DS-WebPayload.zip")
FILES = ["buildings.bin", "relief.bin", "regions.bin", "signposts.bin"]
# Emerald 3DS's tree art (drawn by its author, not the cartridge's): fetched
# with the rest rather than shipped, from a checkout or the repository at a
# pinned commit
TREES = ["tree_crown.png", "tree_trunk.png", "tree_small_crown.png", "tree_small_trunk.png",
         "tree_2_small_crown.png", "tree_2_small_trunk.png"]
TREES_URL = ("https://raw.githubusercontent.com/ZallaxDev/emerald-3ds/"
             "b198c08defb94081ae995796cf75ab8cdb51f2d0/3ds_port/assets/voxel/trees/")


def fetch_trees(out: Path, checkout: Path | None) -> None:
    """The six tree pictures into out/trees/."""
    dest = out / "trees"
    dest.mkdir(parents=True, exist_ok=True)
    for name in TREES:
        local = checkout / "3ds_port" / "assets" / "voxel" / "trees" / name if checkout else None
        if local and local.is_file():
            shutil.copy2(local, dest / name)
            continue
        with urllib.request.urlopen(TREES_URL + name, timeout=60) as response:
            (dest / name).write_bytes(response.read())


def fetch_payload(dest: Path) -> Path:
    """The release's web payload, unpacked into dest (once)."""
    if (dest / "python" / "emerald3ds_builder").is_dir():
        return dest
    dest.mkdir(parents=True, exist_ok=True)
    archive = dest / "WebPayload.zip"
    print("Downloading the Emerald 3DS v0.4.0 payload ...", flush=True)
    with urllib.request.urlopen(PAYLOAD_URL, timeout=120) as response, archive.open("wb") as out:
        shutil.copyfileobj(response, out)
    with zipfile.ZipFile(archive) as z:
        z.extractall(dest)
    archive.unlink()
    return dest


def lua_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_layouts(layouts_json: Path, out: Path) -> None:
    """layouts.json as a Lua table keyed by the 1-based layout id."""
    entries = json.loads(layouts_json.read_text(encoding="utf-8"))["layouts"]
    lines = ["-- generated by bake/bake.py from the ROM's own layout table; do not edit",
             "return {"]
    for i, e in enumerate(entries, start=1):
        if "primary_tileset" not in e:
            continue
        lines.append("  [%d] = { id = %s, w = %d, h = %d, primary = %s, secondary = %s }," % (
            i, lua_string(e.get("id", "")), e.get("width", 0), e.get("height", 0),
            lua_string(e.get("primary_tileset", "")), lua_string(e.get("secondary_tileset", ""))))
    lines.append("}")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")


def bake_from_checkout(args, payload_root: Path, work: Path) -> int:
    """The release builder's input tree, then a checkout's generators on it."""
    from emerald3ds_builder import build, voxel  # noqa: E402
    from emerald3ds_builder.recipe import Recipe  # noqa: E402
    from emerald3ds_builder.rom import load_rom  # noqa: E402
    from emerald3ds_builder.vtree import build_tree  # noqa: E402

    src = args.generators / "3ds_port"
    if not (src / "scripts" / "gen_voxel_buildings.py").is_file():
        print("error: %s is not an Emerald 3DS checkout" % args.generators, file=sys.stderr)
        return 1
    t0 = time.time()

    def progress(fraction, message=""):
        print("%6.1fs %3d%% %s" % (time.time() - t0, int(fraction * 100), message), flush=True)

    rom = load_rom(args.rom)
    payload = build.Payload(payload_root / "payload").for_rom(rom.sha1)
    recipe = Recipe.load(payload.recipe)
    tree = work / "tree"
    tree.mkdir()
    progress(0.0, "Preparing the generators' input tree")
    build_tree(rom.data, recipe, tree, lambda f, d=None: progress(0.2 * f, d or ""))
    gen = work / "voxelgen"
    shutil.copytree(payload.voxelgen, gen)
    for script in (src / "scripts").glob("*.py"):
        shutil.copy2(script, gen / "scripts" / script.name)
    if (src / "assets" / "voxel").is_dir():
        shutil.copytree(src / "assets" / "voxel", gen / "assets" / "voxel", dirs_exist_ok=True)
    voxel.run_generators(tree, gen, [], lambda f, d=None: progress(0.2 + 0.8 * f, d or ""),
                         runner="inprocess")
    args.out.mkdir(parents=True, exist_ok=True)
    for name in FILES:
        made = tree / "3ds_port" / "romfs" / "voxel" / name
        if not made.is_file():
            print("error: the generators did not make %s" % name, file=sys.stderr)
            return 1
        shutil.copy2(made, args.out / name)
    write_layouts(tree / "data" / "layouts" / "layouts.json", args.out / "layouts.lua")
    fetch_trees(args.out, args.generators)
    print("Baked %s into %s from %s (ROM %s)" % (", ".join(FILES + ["layouts.lua"]), args.out,
                                                args.generators, rom.code))
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("rom", type=Path, help="Pokemon Emerald (USA, Europe) ROM")
    parser.add_argument("--payload", type=Path, help="unpacked Emerald3DS-WebPayload.zip")
    parser.add_argument("--out", type=Path, default=HERE.parent / "generated")
    parser.add_argument("--work", type=Path, help="scratch folder (default: the system temp)")
    parser.add_argument("--generators", type=Path,
                        help="an Emerald 3DS checkout whose 3ds_port/scripts and assets/voxel to run")
    args = parser.parse_args()

    payload_root = args.payload or fetch_payload(HERE.parent / "generated" / ".payload")
    sys.path.insert(0, str(payload_root / "python"))
    from emerald3ds_builder import build, pak  # noqa: E402

    work = Path(tempfile.mkdtemp(prefix="e3ds-voxel-", dir=args.work))
    if args.generators:
        try:
            return bake_from_checkout(args, payload_root, work)
        finally:
            shutil.rmtree(work, ignore_errors=True)
    # the builder makes its own tree with a bare mkdtemp: point that inside
    # ours, so the kept tree is found below and removed with the rest
    tempfile.tempdir = str(work)
    try:
        pack = work / "emerald3ds.pak"
        t0 = time.time()

        def progress(fraction, message=""):
            print("%6.1fs %3d%% %s" % (time.time() - t0, int(fraction * 100), message), flush=True)

        # keep_workdir: the layout table the generators read lives in the
        # builder's tree, not in the pack
        summary = build.build_pack(args.rom, build.Payload(payload_root / "payload"), pack,
                                   progress=progress, keep_workdir=True, runner="inprocess",
                                   follower_fetcher=False)
        args.out.mkdir(parents=True, exist_ok=True)
        reader = pak.PakReader(pack)
        for name in FILES:
            (args.out / name).write_bytes(reader.read("voxel/" + name))
        reader.close()
        layouts = next(iter(work.glob("emerald3ds-*/data/layouts/layouts.json")), None)
        if layouts is None:
            print("error: the builder's layout table was not found", file=sys.stderr)
            return 1
        write_layouts(layouts, args.out / "layouts.lua")
        fetch_trees(args.out, None)
        print("Baked %s into %s (ROM %s, release %s)" % (", ".join(FILES + ["layouts.lua"]), args.out,
                                                        summary.get("rom"), summary.get("release")))
        return 0
    finally:
        shutil.rmtree(work, ignore_errors=True)


if __name__ == "__main__":
    sys.exit(main())
